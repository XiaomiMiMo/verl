#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

export PROJECT_NAME="${PROJECT_NAME:-arvo_rl}"
export EXP_NAME="${EXP_NAME:-arvo_train}"

export TRAIN_DATA="${TRAIN_DATA:?set TRAIN_DATA to the ARVO train parquet}"
export VAL_DATA="${VAL_DATA:?set VAL_DATA to the ARVO val parquet}"

export MODEL_PATH="${MODEL_PATH:?set MODEL_PATH to an HF id or a local checkpoint}"

export NNODES="${NNODES:-8}"
export NGPUS_PER_NODE="${NGPUS_PER_NODE:-8}"
export ACTOR_TP="${ACTOR_TP:-8}"
export ACTOR_PP="${ACTOR_PP:-1}"
export ACTOR_CP="${ACTOR_CP:-1}"
export ACTOR_EP="${ACTOR_EP:-1}"
export ROLLOUT_TP="${ROLLOUT_TP:-2}"
export ROLLOUT_DP="${ROLLOUT_DP:-1}"

export MAXLEN="${MAXLEN:-262144}"
export PROMPT_LENGTH="${PROMPT_LENGTH:-16384}"
export RESPONSE_LENGTH="${RESPONSE_LENGTH:-$((MAXLEN - PROMPT_LENGTH))}"
export PPO_MAX_TOKEN_LEN_PER_GPU="${PPO_MAX_TOKEN_LEN_PER_GPU:-${MAXLEN}}"

export TRAIN_BATCH_SIZE="${TRAIN_BATCH_SIZE:-64}"
export PPO_MINI_BATCH_SIZE="${PPO_MINI_BATCH_SIZE:-64}"
export ROLLOUT_N="${ROLLOUT_N:-16}"

export ACTOR_LR="${ACTOR_LR:-1e-6}"
export MEGATRON_OFFLOAD="${MEGATRON_OFFLOAD:-True}"
export TOTAL_EPOCHS="${TOTAL_EPOCHS:-5}"
export TOTAL_TRAINING_STEPS="${TOTAL_TRAINING_STEPS:-300}"

export ROLLOUT_TEMPERATURE="${ROLLOUT_TEMPERATURE:-1.0}"
export ROLLOUT_TOP_P="${ROLLOUT_TOP_P:-1.0}"
export ROLLOUT_TOP_K="${ROLLOUT_TOP_K:--1}"
export ROLLOUT_GPU_MEM_UTIL="${ROLLOUT_GPU_MEM_UTIL:-0.78}"
export ROLLOUT_MAX_RUNNING_REQUESTS="${ROLLOUT_MAX_RUNNING_REQUESTS:-64}"
export AGENT_NUM_WORKERS="${AGENT_NUM_WORKERS:-128}"
export FORMAT="${FORMAT:-qwen3_coder}"

export TRAINER_MODE="${TRAINER_MODE:-colocate_async}"
export NUM_WARMUP_BATCHES="${NUM_WARMUP_BATCHES:-1}"
export MAX_OFF_POLICY_THRESHOLD="${MAX_OFF_POLICY_THRESHOLD:-8}"
export MAX_OFF_POLICY_STRATEGY="${MAX_OFF_POLICY_STRATEGY:-drop}"

export DROP_INFRA_FROM_GROUP="${DROP_INFRA_FROM_GROUP:-1}"
export INVALID_REWARD_FOR_INFRA="${INVALID_REWARD_FOR_INFRA:-false}"
export FILTER_GROUPS_ENABLE="${FILTER_GROUPS_ENABLE:-True}"
export FILTER_GROUPS_METRIC="${FILTER_GROUPS_METRIC:-reward}"

export ENV_SETUP_TIMEOUT="${ENV_SETUP_TIMEOUT:-900}"
export TRAJECTORY_TIMEOUT="${TRAJECTORY_TIMEOUT:-28800}"
export ENV_NUM_CPUS="${ENV_NUM_CPUS:-0.125}"
export FAIL_ON_ENV_SETUP_ERROR="${FAIL_ON_ENV_SETUP_ERROR:-false}"

export SAVE_FREQ="${SAVE_FREQ:-1}"
export TEST_FREQ="${TEST_FREQ:-999}"
export MAX_CKPT_TO_KEEP="${MAX_CKPT_TO_KEEP:-1000}"
export RESUME_MODE="${RESUME_MODE:-disable}"

exec bash "${REPO_ROOT}/recipes/arvo/run_arvo.sh" "$@"
